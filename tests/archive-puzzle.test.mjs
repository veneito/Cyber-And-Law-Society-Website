import assert from 'node:assert/strict';
import { TRANSACTIONS, ARCHIVE_FILES, archiveHash, decryptArchive, recoveredFiles, runArchiveCommand, archiveProgress, importArchiveKit, VAULT_URL } from '../src/components/archivePuzzle.ts';
import { runOracleCommand } from '../src/components/oraclePuzzle.ts';
for (const tx of TRANSACTIONS) assert.equal(tx.input, tx.outputs.reduce((n, output) => n + output.value, 0) + tx.fee);
const first = TRANSACTIONS.find(tx => tx.from === 'bc1q-donor-884' && tx.time.includes('03:14:00'));
assert.ok(first);
const payment = first.outputs.find(output => output.value === 150000);
const relay = TRANSACTIONS.find(tx => tx.id === payment.spent);
const custody = relay.outputs.find(output => output.address !== relay.from);
const last = TRANSACTIONS.find(tx => tx.id === custody.spent);
assert.equal(await runOracleCommand(`hex ${last.op}`, false), `${VAULT_URL}|RELAY-884`);
assert.equal(new Date('2026-10-28T22:14:00-05:00').toISOString(), '2026-10-29T03:14:00.000Z');
assert.equal(await archiveHash(ARCHIVE_FILES['archive/custodian.txt']), 'c856ef9afaa5405d6936aed31c170295a8d63710cd028d8e78cffdd262ec2ff6');
assert.notEqual(await archiveHash(ARCHIVE_FILES['archive/forged.txt']), await archiveHash(ARCHIVE_FILES['archive/custodian.txt']));
assert.equal(await runArchiveCommand('cat archive/auth.log'), null);
globalThis.window = new EventTarget();
importArchiveKit();
assert.match(await runOracleCommand('ls'), /archive\/disk.img/);
assert.match(await runOracleCommand('strings archive/disk.img'), /BEGIN_FILE vessel.cfg/);
assert.match(await runOracleCommand('carve archive/disk.img vessel.cfg'), /Recovered/);
assert.match(recoveredFiles['recovered/vessel.cfg'], /key_salt=EMBER/);
assert.match(await runOracleCommand('cat recovered/vessel.cfg'), /formula=receipt\|issued_at_utc\|key_salt/);
assert.match(await runOracleCommand('sha256file archive/custodian.txt'), /^c856ef/);
assert.equal(archiveProgress.verified, true);
assert.match(await runOracleCommand('carve archive/disk.img missing.cfg'), /ERROR/);
assert.match(await runOracleCommand('decrypt archive/sealed.json "wrong"'), /Authentication failed/);
assert.equal(archiveProgress.decrypted, false);
const plaintext = await decryptArchive('HD-884|2026-10-29T03:14:00Z|EMBER');
assert.match(plaintext, /FRAGMENT=CINDER/);
assert.match(plaintext, /Julieta is alive/);
assert.match(await runOracleCommand('decrypt archive/sealed.json "HD-884|2026-10-29T03:14:00Z|EMBER"'), /FRAGMENT=CINDER/);
assert.equal(archiveProgress.decrypted, true);
assert.match(recoveredFiles['recovered/case.txt'], /LOCATION=/);
console.log('Wallet trail, false mirror, carving and authenticated decryption checks passed.');

const { searchTransactions } = await import('../src/components/archivePuzzle.ts');
assert.deepEqual(searchTransactions(''),[]);
assert.deepEqual(searchTransactions('unknown'),[]);
assert.equal(searchTransactions('bc1q-donor-884')[0].id,'tx-884-a');
assert.equal(searchTransactions('tx-884-b')[0].id,'tx-884-b');
assert.equal(searchTransactions('bc1q-relay-a').length,2);
