import assert from 'node:assert/strict';
import { ORACLE_FILES, ORACLE_RESPONSE, sha256, xorDecode, reassemble, acceptOracleResponse, runOracleCommand } from '../src/components/oraclePuzzle.ts';
const hex = reassemble(ORACLE_FILES['packets.log'], '7A');
assert.equal(hex, '233129282826263b780e071d170c1f742b2c262c207e7f7c7172');
assert.ok(ORACLE_FILES['manifest.txt'].includes(await sha256(hex)));
const key = await runOracleCommand('base64 RUNITw==', true);
assert.equal(key, 'ECHO');
assert.equal(xorDecode(hex, key), 'fragment=MORROW;nonce=7341');
assert.equal(await sha256('7341:041:MORROW'), ORACLE_RESPONSE);
assert.equal(acceptOracleResponse('MORROW'), false);
assert.equal(acceptOracleResponse(await sha256('7341:041:MORROW')), true);
assert.match(await runOracleCommand('cat packets.log', false), /No evidence/);
assert.match(await runOracleCommand('grep "visitor=041" access.log', true), /stream=7A/);
assert.match(await runOracleCommand('cat secrets', true), /File not found/);
assert.match(await runOracleCommand('xor zz ECHO', true), /ERROR/);
assert.match(await runOracleCommand('base64 %%%', true), /ERROR/);
assert.equal(await runOracleCommand('reassemble packets.log 7A', true), hex);
assert.equal(await runOracleCommand('sha256 "7341:041:MORROW"', true), ORACLE_RESPONSE);
assert.throws(() => reassemble('stream=7A seq=0008 checksum=OK hex=abcd', '7A'), /Missing/);
assert.throws(() => reassemble('stream=7A seq=0000 checksum=OK hex=abcd\nstream=7A seq=0000 checksum=OK hex=eeee', '7A'), /Conflicting/);
console.log('Oracle terminal and full evidence-chain checks passed.');
